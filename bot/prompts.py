def _sections(name: str) -> dict[str, str]:
    text = (ROOT / name).read_text(encoding="utf-8")
    parts = re.split(r"(?m)^(?=## )", text)[1:]
    return {p[3:].split("\n", 1)[0].strip(): p.strip() for p in parts}


