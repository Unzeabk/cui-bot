def _recent_txt(recent: list[dict]) -> str:
    if not recent:
        return "(пока нет)"
    return "\n".join(
        f"- {r.get('time','')} | {r.get('rubric','')} | форма: {r.get('form','')} | "
        f"оптики: {', '.join(r.get('optics', []))} | тема: {r.get('topic_key','')} | «{r.get('headline','')}» | "
        f"флай: «{r.get('fly','')}» | финал: «{r.get('final','')}»"
        for r in recent
    )


def rubric_balance(recent: list[dict]) -> str:
    from datetime import datetime, timedelta, timezone
    now = datetime.now(timezone.utc)
    week = {k: 0 for k in RUBRICS}
    day = {k: 0 for k in RUBRICS}
    for r in recent:
        k = r.get("rubric")
        if k not in week:
            continue
        week[k] += 1
        try:
            if now - datetime.fromisoformat(r["time_iso"]) <= timedelta(hours=24):
                day[k] += 1
        except (KeyError, ValueError):
            pass
    order = sorted(RUBRICS, key=lambda k: (week[k], day[k]))
    return "\n".join(f"- {k} ({RUBRICS[k][0]}): за сутки {day[k]}, за неделю {week[k]}" for k in order)


def topic_user_message(items: list[dict], recent: list[dict]) -> str:
    lines = [f"{i}. [{it['source'][:30]}] {it['title']} — {it['summary'][:110]}" for i, it in enumerate(items)]
    return "Баланс рубрик (сверху — те, которых давно не было):\n" + rubric_balance(recent) + "\n\nНедавние заметки (темы не повторять):\n" + _recent_txt(recent[-20:]) + "\n\nНовости за 48 часов:\n" + "\n".join(lines)


def writer_user_message(today: str, recent: list[dict], materials: list[dict], rubric: str = "") -> str:
    rule = f"Рубрика заметки: {rubric}. " if rubric in RUBRICS else ""
    if recent:
        last = recent[-1]
        rule += (
            f"Последняя заметка была в рубрике {last.get('rubric')} в форме «{last.get('form')}» "
            f"с главной оптикой «{(last.get('optics') or [''])[0]}». Возьми другую рубрику, другую форму и другую главную оптику. "
            "Если сегодня уже был «невозможный факт», эту форму не бери."
        )
    mats = []
    for i, m in enumerate(materials):
        tag = "ГЛАВНЫЙ МАТЕРИАЛ" if i == 0 else f"Дополнительный материал {i}"
        mats.append(f"=== {tag} ===\nИсточник: {m['source']}\nURL: {m['link']}\nЗаголовок: {m['title']}\nТекст:\n{m['text']}")
    return (
        f"Сегодня {today}. Напиши одну заметку по материалам ниже.\n\n"
        f"Недавние заметки:\n{_recent_txt(recent[-15:])}\n\n{rule}\n\n" + "\n\n".join(mats)
    )


